/** 今の言語の文字。既定は日本語(テストもこれで読む) */
export const S: Strings = { ...JA };

/** Obsidian の言語(getLanguage())で S を切り替える。ja 以外は英語 */
export function useLanguage(lang: string): void {
	Object.assign(S, lang.toLowerCase().startsWith("ja") ? JA : EN);
}
